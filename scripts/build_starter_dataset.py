QUESTION_FORMS = [
    lambda q: q,
    lambda q: "Объясни простыми словами: " + q[0].lower() + q[1:],
    lambda q: "Расскажи, пожалуйста: " + q[0].lower() + q[1:],
    lambda q: "Мне нужно узнать — " + q[0].lower() + q[1:],
]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="data/raw/starter_dialogues.jsonl")
    args = parser.parse_args()
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for topic, question, answer in FACTS:
        for variant, make_question in enumerate(QUESTION_FORMS):
            rows.append({
                "id": f"{topic}-{variant + 1}",
                "messages": [
                    {"role": "user", "content": make_question(question)},
                    {"role": "assistant", "content": answer},
                ],
            })
    with output.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Created {len(rows)} curated starter dialogues.")
    print(f"Topics: {len(FACTS)}")
    print(f"Saved: {output}")
    print("This is a small seed set for pipeline testing, not a knowledge-complete dataset.")


if __name__ == "__main__":
    main()
